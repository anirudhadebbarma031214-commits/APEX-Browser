-- ANI CHAT setup for Supabase
-- Run once in Supabase Dashboard > SQL Editor > New query.
-- Uses Supabase Auth + row-level security: only the sender and recipient can read a DM.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  created_at timestamptz not null default now(),
  constraint username_format check (username is null or username ~ '^[a-z0-9_]{3,20}$')
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now(),
  constraint no_self_message check (sender_id <> recipient_id)
);

create index if not exists messages_sender_recipient_time
  on public.messages(sender_id, recipient_id, created_at);
create index if not exists messages_recipient_sender_time
  on public.messages(recipient_id, sender_id, created_at);

alter table public.profiles enable row level security;
alter table public.messages enable row level security;

drop policy if exists "Authenticated users can find usernames" on public.profiles;
create policy "Authenticated users can find usernames"
  on public.profiles for select to authenticated using (true);

drop policy if exists "Users can create their own profile" on public.profiles;
create policy "Users can create their own profile"
  on public.profiles for insert to authenticated with check (auth.uid() = id);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
  on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "DM participants can read messages" on public.messages;
create policy "DM participants can read messages"
  on public.messages for select to authenticated
  using (auth.uid() = sender_id or auth.uid() = recipient_id);

drop policy if exists "Users can send messages as themselves" on public.messages;
create policy "Users can send messages as themselves"
  on public.messages for insert to authenticated
  with check (
    auth.uid() = sender_id
    and sender_id <> recipient_id
    and exists (select 1 from public.profiles p where p.id = recipient_id and p.username is not null)
  );

-- Create a profile row automatically whenever someone signs up.
create or replace function public.handle_new_ani_chat_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id) values (new.id)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_ani_chat on auth.users;
create trigger on_auth_user_created_ani_chat
  after insert on auth.users
  for each row execute procedure public.handle_new_ani_chat_user();

-- Enable realtime updates for new messages.
do $$
begin
  alter publication supabase_realtime add table public.messages;
exception
  when duplicate_object then null;
  when undefined_object then raise notice 'supabase_realtime publication not found; enable Realtime for public.messages in the Supabase dashboard.';
end $$;

grant usage on schema public to authenticated;
grant select, insert, update on public.profiles to authenticated;
grant select, insert on public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;
